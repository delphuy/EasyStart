    /// <summary>取一串字符的拼音首字母（非汉字回退大写）</summary>
    public static string Initial(string s)
    {
        if (string.IsNullOrEmpty(s)) return "";
        var buf = new char[s.Length];
        for (int i = 0; i < s.Length; i++)
        {
            char c = s[i];
            buf[i] = _map.TryGetValue(c, out char p) ? p : char.ToUpperInvariant(c);
        }
        return new string(buf);
    }

    /// <summary>是否匹配（子串或拼音首字母子串）</summary>
    public static bool Match(string name, string query)
    {
        if (string.IsNullOrEmpty(query)) return true;
        if (name.Contains(query, System.StringComparison.OrdinalIgnoreCase)) return true;
        return Initial(name).Contains(query, System.StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>排序分：前缀 &gt; 拼音前缀 &gt; 子串 &gt; 拼音子串（越大越前）</summary>
    public static int Rank(string name, string query)
    {
        if (string.IsNullOrEmpty(query)) return 0;
        if (name.StartsWith(query, System.StringComparison.OrdinalIgnoreCase)) return 4;
        string ini = Initial(name);
        if (ini.StartsWith(query, System.StringComparison.OrdinalIgnoreCase)) return 3;
        if (name.Contains(query, System.StringComparison.OrdinalIgnoreCase)) return 2;
        if (ini.Contains(query, System.StringComparison.OrdinalIgnoreCase)) return 1;
        return 0;
    }
